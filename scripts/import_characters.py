#!/usr/bin/env python3
"""Import the 17-pose illustrated character ZIP without third-party packages."""
from __future__ import annotations
import hashlib
import json
import pathlib
import re
import struct
import sys
import zipfile

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "assets" / "characters" / "generated"
REGISTRY = ROOT / "data" / "character-assets.js"
HTML = ROOT / "index.html"
EXPECTED = (
  "C01_L01", "C01_L02", "C01_L03", "C01_L04", "C01_L05", "C01_L06",
  "C02_Q01", "C02_Q02", "C02_Q03", "C02_Q04",
  "C03_D01", "C03_D02", "C03_D03", "C03_D04",
  "C04_N01", "C04_N02", "C04_N03",
)
MAX_ARCHIVE = 35 * 1024 * 1024
MAX_IMAGE = 8 * 1024 * 1024


def main() -> None:
    archive = pathlib.Path(sys.argv[1]) if len(sys.argv) == 2 else ROOT / "uploads" / "characters.zip"
    if not archive.is_file():
        raise SystemExit(f"Missing ZIP: {archive}. Upload to uploads/characters.zip first.")
    if archive.stat().st_size > MAX_ARCHIVE:
        raise SystemExit("Archive too large: limit is 35 MB.")
    payload: dict[str, bytes] = {}
    with zipfile.ZipFile(archive) as z:
        for item in z.infolist():
            if item.is_dir():
                continue
            if item.flag_bits & 0x1:
                raise SystemExit("Encrypted ZIP is not supported.")
            if item.file_size > MAX_IMAGE:
                raise SystemExit(f"File is too large: {item.filename}")
            path = pathlib.PurePosixPath(item.filename.replace("\\", "/"))
            if ".." in path.parts or path.is_absolute():
                raise SystemExit(f"Unsafe filename: {item.filename}")
            if path.name in {"manifest.json", "README.txt"}:
                continue
            if not re.fullmatch(r"C0[1-4]_[LQDN]\d\d\.png", path.name):
                raise SystemExit(f"Unexpected file in ZIP: {item.filename}")
            stem = path.stem
            if stem not in EXPECTED or stem in payload:
                raise SystemExit(f"Unexpected or repeated character file: {item.filename}")
            raw = z.read(item)
            if len(raw) < 33 or raw[:8] != b"\x89PNG\r\n\x1a\n" or raw[12:16] != b"IHDR":
                raise SystemExit(f"Not a real PNG: {item.filename}")
            width, height, bitdepth, color_type = struct.unpack(">IIBB", raw[16:26])
            if width < 128 or height < 128 or width > 4096 or height > 4096 or bitdepth != 8 or color_type != 6:
                raise SystemExit(f"Expect 8-bit RGBA PNG within 128-4096px: {item.filename}")
            payload[stem] = raw
    missing = sorted(set(EXPECTED) - payload.keys())
    if missing:
        raise SystemExit(f"Missing {len(missing)} required images: {', '.join(missing)}")
    OUTPUT.mkdir(parents=True, exist_ok=True)
    for stem in EXPECTED:
        (OUTPUT / f"{stem}.png").write_bytes(payload[stem])
    sha = hashlib.sha256()
    for stem in EXPECTED:
        sha.update(stem.encode("ascii"))
        sha.update(hashlib.sha256(payload[stem]).digest())
    revision = sha.hexdigest()[:12]
    files = {stem: f"./assets/characters/generated/{stem}.png?v={revision}" for stem in EXPECTED}
    js = "/* Automatically generated by scripts/import_characters.py. Do not edit manually. */\n"
    js += "window.JINGCAI_ASSETS = " + json.dumps({"ready": True, "revision": revision, "files": files}, ensure_ascii=False, indent=2) + ";\n"
    REGISTRY.write_text(js, encoding="utf-8")
    html = HTML.read_text(encoding="utf-8")
    new_html, count = re.subn(r"(data/character-assets\.js\?v=)[A-Za-z0-9_-]+", r"\g<1>" + revision, html)
    if count != 1:
        raise SystemExit("Expected exactly one asset registry <script> in index.html.")
    HTML.write_text(new_html, encoding="utf-8")
    print(f"Validated {len(EXPECTED)} transparent PNG images; asset revision {revision}.")
    print("Updated: assets/characters/generated/, data/character-assets.js, index.html")


if __name__ == "__main__":
    main()
